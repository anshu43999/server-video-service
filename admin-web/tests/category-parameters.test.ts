it('retains the draft after a revision conflict and requires a read before further writes',async()=>{
  const parameters=vi.spyOn(modelsApi,'parameters').mockResolvedValueOnce({...profile(),revision:7,publishedRevision:6}).mockResolvedValueOnce({...profile(),revision:8,publishedRevision:6})
  const save=vi.spyOn(modelsApi,'saveParameters').mockRejectedValue(new ApiError({status:409,code:'revision_conflict',message:'档案修订冲突'}))
  const publish=vi.spyOn(modelsApi,'publishParameters'),reset=vi.spyOn(modelsApi,'resetParameters')
  const wrapper=mount(ParametersDialog,{props:{model,initialPlatform:'server'},global});await flushPromises()
  const confidence=()=>wrapper.findAllComponents({name:'UiInput'}).find(input=>input.props('type')==='number')!
  confidence().vm.$emit('update:modelValue',.4);await flushPromises()
  await wrapper.find('form').trigger('submit');await flushPromises()
  expect(save).toHaveBeenCalledTimes(1)
  expect(confidence().props('modelValue')).toBe(.4)
  expect(wrapper.find('.parameter-editor-state').text()).toContain('需要重新核验')
  for(const label of ['保存草稿','发布参数','重置草稿'])expect(wrapper.findAll('button').find(button=>button.text()===label)!.attributes('disabled')).toBeDefined()
  await wrapper.find('form').trigger('submit');await flushPromises()
  expect(save).toHaveBeenCalledTimes(1);expect(publish).not.toHaveBeenCalled();expect(reset).not.toHaveBeenCalled()
  await wrapper.findAll('button').find(button=>button.text()==='重新读取档案')!.trigger('click');await flushPromises()
  expect(parameters).toHaveBeenLastCalledWith('model','server',expect.any(AbortSignal),'1')
  expect(wrapper.find('.parameter-editor-meta').text()).toContain('草稿修订r8')
  expect(confidence().props('modelValue')).toBe(.35)
  expect(wrapper.findAll('button').find(button=>button.text()==='保存草稿')!.attributes('disabled')).toBeUndefined()
  wrapper.unmount()
})
